import { existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { extname, join } from 'node:path';

/**
 * Safety net for E2E artifacts (H-02). Playwright traces and failure snapshots can capture request bodies and the
 * text of the page (passwords, the TOTP secret on the enrolment screen, invitation links). Text artifacts are
 * scanned and redacted in place; opaque archives (trace.zip) are deleted because they cannot be inspected.
 * Findings never include the secret itself.
 */
export type SecretKind = 'invitation-token' | 'otpauth-uri' | 'known-secret' | 'generated-password' | 'opaque-archive';

export interface Finding {
  file: string;
  kind: SecretKind;
}

const TEXT_EXTENSIONS = new Set(['.md', '.txt', '.json', '.log', '.html', '.htm', '.yml', '.yaml', '.xml', '.csv']);
const OPAQUE_ARCHIVES = new Set(['.zip']);

const PATTERNS: { kind: SecretKind; regex: RegExp }[] = [
  // New (#TOKEN) and legacy (/TOKEN) invitation links; tokens are 32 random bytes in base64url (43 chars).
  { kind: 'invitation-token', regex: /registro\/invitacion[#/][A-Za-z0-9_-]{43}/g },
  { kind: 'otpauth-uri', regex: /otpauth:\/\/[^\s"'<>)]+/g },
  // Passwords generated by these specs (Reg-/Fam- + 16 hex).
  { kind: 'generated-password', regex: /\b(?:Reg|Fam)-[0-9a-f]{16}\b/g },
];

function walk(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function scanArtifacts(dirs: string[], options: { knownSecrets: (string | undefined)[]; mode: 'check' | 'redact' }): Finding[] {
  const known = options.knownSecrets.filter((s): s is string => !!s && s.length >= 8);
  const patterns = [...PATTERNS, ...known.map((secret) => ({ kind: 'known-secret' as const, regex: new RegExp(escapeRegExp(secret), 'g') }))];
  const findings: Finding[] = [];

  for (const file of dirs.flatMap(walk)) {
    const extension = extname(file).toLowerCase();
    if (OPAQUE_ARCHIVES.has(extension)) {
      findings.push({ file, kind: 'opaque-archive' });
      if (options.mode === 'redact') rmSync(file, { force: true });
      continue;
    }
    if (!TEXT_EXTENSIONS.has(extension)) continue;
    let text = readFileSync(file, 'utf8');
    let changed = false;
    for (const { kind, regex } of patterns) {
      regex.lastIndex = 0;
      if (!regex.test(text)) continue;
      findings.push({ file, kind });
      if (options.mode === 'redact') {
        text = text.replace(regex, kind === 'invitation-token' ? 'registro/invitacion#[REDACTED]' : '[REDACTED]');
        changed = true;
      }
    }
    if (changed) writeFileSync(file, text);
  }
  return findings;
}
